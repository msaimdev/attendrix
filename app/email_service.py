import smtplib
from email.message import EmailMessage

from app.config import settings


class EmailService:
    """
    Handle outgoing email for the Face Attendance System.

    SMTP credentials are loaded from application settings.

    Responsibilities:
        - connect to the configured SMTP server
        - send plain-text emails
        - build the daily attendance report email

    Attendance calculation remains completely separate
    from this service.
    """

    def __init__(self):
        self.smtp_host = settings.smtp_host
        self.smtp_port = settings.smtp_port
        self.smtp_username = settings.smtp_username
        self.smtp_password = settings.smtp_password
        self.smtp_from = settings.smtp_from

    # ========================================================
    # SEND EMAIL
    # ========================================================

    def send_email(
        self,
        recipient: str,
        subject: str,
        body: str,
    ):
        """
        Send a plain-text email through the configured SMTP
        server.

        Returns:

            {
                "success": True,
                "message": "Email sent successfully.",
            }

        or:

            {
                "success": False,
                "message": "...",
            }
        """

        if not recipient:
            return {
                "success": False,
                "message": (
                    "No recipient email address was provided."
                ),
            }

        message = EmailMessage()

        message["Subject"] = subject
        message["From"] = self.smtp_from
        message["To"] = recipient

        message.set_content(body)

        try:

            with smtplib.SMTP(
                self.smtp_host,
                self.smtp_port,
                timeout=30,
            ) as smtp:

                smtp.ehlo()

                smtp.starttls()

                smtp.ehlo()

                smtp.login(
                    self.smtp_username,
                    self.smtp_password,
                )

                smtp.send_message(message)

            return {
                "success": True,
                "message": "Email sent successfully.",
            }

        except Exception as error:

            print()
            print(
                "ERROR: Email sending failed."
            )

            print(
                f"Email error: {error}"
            )

            print()

            return {
                "success": False,
                "message": (
                    "Email sending failed."
                ),
            }

    # ========================================================
    # BUILD ATTENDANCE REPORT EMAIL
    # ========================================================

    def build_attendance_report_email(
        self,
        report,
        school_name,
    ):
        """
        Build a plain-text daily attendance report email.

        The attendance figures come directly from the existing
        AttendanceManager.generate_report() result.

        Args:
            report:
                Attendance report dictionary generated by
                AttendanceManager.generate_report().

            school_name:
                Configured school name.

        Returns:
            Plain-text email body.
        """

        date = report["date"]

        lines = [
            f"{school_name}",
            "Daily Attendance Report",
            "=" * 40,
            "",
            f"Date: {date}",
            "",
            "SUMMARY",
            "-" * 40,
            f"Total Students: {report['total_students']}",
            f"Expected Students: {report['expected_students']}",
            f"Present: {report['present']}",
            f"Absent: {report['absent']}",
            f"On Leave: {report['on_leave']}",
            f"Not Expected: {report['not_expected']}",
            (
                "Attendance Percentage: "
                f"{report['attendance_percentage']:.2f}%"
            ),
            "",
            "CLASS SUMMARY",
            "-" * 40,
        ]

        for class_name, summary in sorted(
            report["classes"].items()
        ):
            lines.extend(
                [
                    "",
                    f"Class: {class_name}",
                    (
                        "  Total Students: "
                        f"{summary['total_students']}"
                    ),
                    (
                        "  Expected Students: "
                        f"{summary['expected_students']}"
                    ),
                    (
                        "  Present: "
                        f"{summary['present']}"
                    ),
                    (
                        "  Absent: "
                        f"{summary['absent']}"
                    ),
                    (
                        "  On Leave: "
                        f"{summary['on_leave']}"
                    ),
                    (
                        "  Not Expected: "
                        f"{summary['not_expected']}"
                    ),
                ]
            )

        lines.extend(
            [
                "",
                "=" * 40,
                "Face Attendance System",
            ]
        )

        return "\n".join(lines)